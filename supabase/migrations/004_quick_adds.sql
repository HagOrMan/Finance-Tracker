-- ============================================================================
-- 004_quick_adds.sql — saved presets for the quick-add sheet.
-- Safe to re-run. Run AFTER 003_subscriptions.sql.
--
-- A quick add is a TEMPLATE, not a spend record — like a subscription, nothing
-- in the app's math reads this table. Picking one only pre-fills the quick-add
-- form; what lands on the ledger is an ordinary receipt or disbursement, with
-- no link back here. Deleting a preset therefore never touches history.
--
-- AFTERWARDS
--   Regenerate src/types/database.ts (command in 002_mutable_rows.sql). The
--   hand-written `quick_adds` entry there should come out identical.
-- ============================================================================

create table if not exists finance_tracker.quick_adds (
    id           bigint generated by default as identity primary key,
    kind         text    not null check (kind in ('receipt','disbursement')),
    name         text    not null,               -- chip label, e.g. "Rent – Alex"
    counterparty text    not null,               -- receipt store / disbursement entity
    category     text,                           -- receipts only
    amount       numeric check (amount > 0),     -- null = enter it each time
    note         text,                           -- receipt note / disbursement reason
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),

    -- A receipt can't be added without a category, so a receipt preset without
    -- one would fill a form that can't submit. Disbursements have no category.
    constraint quick_adds_category_matches_kind check (
        (kind = 'receipt' and category is not null)
        or (kind = 'disbursement' and category is null)
    )
);

drop trigger if exists quick_adds_set_updated_at on finance_tracker.quick_adds;
create trigger quick_adds_set_updated_at
    before update on finance_tracker.quick_adds
    for each row execute function finance_tracker.set_updated_at();

-- A custom schema inherits NO default privileges (see finance_tracker_schema.sql
-- §4) — a new table without these lines is unreachable, secret key or not.
alter table finance_tracker.quick_adds enable row level security;
revoke all on finance_tracker.quick_adds from public, anon, authenticated;
grant select, insert, update, delete on finance_tracker.quick_adds to service_role;
