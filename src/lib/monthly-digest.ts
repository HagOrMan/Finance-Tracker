/**
 * Total subscription charges falling in `[from, to]`.
 *
 * Walks each schedule forward from `charges_generated`, which is where the next
 * unwritten charge starts. Charge dates increase monotonically, so the loop
 * exits on the first one past the window; the iteration cap is a backstop
 * against a mistyped daily interval, not a real bound.
 *
 * Paused subscriptions are skipped — an inactive schedule owes nothing.
 */
function projectedSubscriptionSpend(
  subscriptions: readonly Subscription[],
  from: string,
  to: string,
): number {
  const MAX_STEPS = 2000;
  let total = 0;

  for (const sub of subscriptions) {
    if (!sub.active) continue;
    for (let step = 0; step < MAX_STEPS; step += 1) {
      const date = nthChargeDate(
        sub.start_date,
        sub.interval_unit,
        sub.interval_count,
        sub.charges_generated + step,
      );
      if (date > to) break;
      if (date >= from) total += sub.price;
    }
  }

  return total;
}

