/** Which of the three rules put a receipt in the big-spenders table. */
export type BigSpenderReason = "floor" | "category-relative" | "share-of-month";

export interface BigSpenderRow {
  receiptId: number;
  date: string;
  store: string;
  category: string;
  /** Net — `actual_price`, so refunds have already come off. */
  amount: number;
  /** Every rule it satisfied. Never empty. */
  reasons: BigSpenderReason[];
  /** The category's trailing median receipt. Null unless the relative rule fired. */
  categoryMedian: number | null;
  /** e.g. 3.4, for "3.4× typical Transportation". Null unless the relative rule fired. */
  multipleOfMedian: number | null;
  /** 0..1 of the month's all-in spend. */
  shareOfAllIn: number;
  /** False for Travel/School/Rent — those sit outside the habitual figure. */
  inHabitual: boolean;
  /**
   * Generated by a subscription. Exempt from the relative and share rules, so a
   * recurring charge can only appear here by clearing the absolute floor — and
   * when it does, it is labelled, because it is the opposite of a one-off.
   */
  recurring: boolean;
}

export interface CategoryGridRow {
  category: string;
  /** Same order and length as `CategoryMonthGrid.months`. Null = month predates the ledger. */
  values: (number | null)[];
  /** Sum across the usable months. What the top-N ranking uses. */
  total: number;
}

export interface CategoryMonthGrid {
  /** Oldest first, ending with the digest's own month. */
  months: string[];
  rows: CategoryGridRow[];
  /** The tail beyond `DIGEST_MAX_GRID_CATEGORIES`, summed per month. Null when nothing was rolled up. */
  otherRow: CategoryGridRow | null;
  /** Column totals. Null where the month predates the ledger. */
  totals: (number | null)[];
}

/** Which estimator produced a figure — the digest states it rather than implying one. */
export type EstimatorRule = "trimmed-mean" | "median";

export type TrendDirection = "rising" | "falling";

export interface ProjectedCategory {
  category: string;
  /** Per-month point estimate, one-offs already removed. */
  perMonth: number;
  /** p25 / p75 across the usable baseline months. Equal to `perMonth` when only one month is usable. */
  low: number;
  high: number;
  rule: EstimatorRule;
  usableMonths: number;
  /** Set when the last-3-month median diverges from the prior-3 by more than the threshold. */
  trend: TrendDirection | null;
}

export interface ProjectionTotal {
  total: number;
  low: number;
  high: number;
}

export interface Projection {
  /**
   * The month the next-month figure covers, "YYYY-MM".
   *
   * The month *after* the digest's — so a July digest, mailed on 3 August,
   * projects August. That month is already three days old when it arrives, and
   * projecting it anyway is deliberate: the estimate is a whole-month figure,
   * and the month you are living in is the one you are budgeting.
   */
  nextMonth: string;
  /** Whole calendar months the horizon covers, starting at `nextMonth`. */
  horizonMonths: number;
  /** Last month of the horizon, "YYYY-MM". */
  horizonThrough: string;

  categories: ProjectedCategory[];

  /** Estimated from the ledger. */
  habitualPerMonth: ProjectionTotal;
  /**
   * **Computed, not estimated** — from each subscription's schedule via
   * `nthChargeDate`. Carries no spread because it carries no uncertainty.
   */
  subscriptionsNextMonth: number;
  subscriptionsHorizon: number;

  /** habitual + subscriptions. Excludes rent, school and travel by construction. */
  nextMonthTotal: ProjectionTotal;
  horizonTotal: ProjectionTotal;

  /**
   * Average monthly one-off spend in *habitual* categories over the baseline.
   *
   * Deliberately **outside** every total above: one-offs are unforecastable, but
   * "unforecastable" is not "won't happen", and a budget built without a buffer
   * is short every time a car repair lands. Excluded-category one-offs are not
   * counted — the projection already says it omits rent, school and travel, so
   * folding tuition in here would double-count the omission.
   */
  oneOffBuffer: number;
}

export interface NamedTotal {
  /** The most-used spelling in the group — same display rule as `/stores`. */
  name: string;
  total: number;
  count: number;
}

/**
 * A category's month-over-baseline change, split into the two things that can
 * cause it.
 *
 * `frequencyEffect + ticketEffect === deltaSpent` exactly. The interaction term
 * is split evenly between them (the symmetric decomposition) rather than being
 * dumped on whichever is computed second, which would make the attribution
 * depend on argument order.
 *
 * **One-offs are stripped from both sides.** They have their own table, and a
 * single brake job would otherwise read as a ruinous rise in average ticket.
 */
export interface CategoryChangeRow {
  category: string;
  /** This month, one-offs removed. */
  spent: number;
  receiptCount: number;
  /** What was removed, so this reconciles against the grid. */
  oneOffsRemoved: number;
  baselineSpent: number;
  /** Mean receipts per usable baseline month. Fractional on purpose. */
  baselineCount: number;
  avgTicket: number;
  baselineAvgTicket: number;
  deltaSpent: number;
  /** Portion of `deltaSpent` from going more or less often. */
  frequencyEffect: number;
  /** Portion from each visit costing more or less. */
  ticketEffect: number;
}

export interface QuietWinRow {
  category: string;
  spent: number;
  baseline: number;
  /** Negative — this is the amount it came in under. */
  delta: number;
}

export interface EatingOutSplit {
  stressed: number;
  social: number;
  /** stressed / (stressed + social). Null when both are zero. */
  stressedShare: number | null;
  /** The same ratio across the usable baseline months. Null when there is nothing to compare. */
  baselineStressedShare: number | null;
}

export interface MonthlyDigest {
  /** "YYYY-MM" — the completed month this covers. */
  month: string;
  /** Inclusive, plain dates. Always the whole month; there is no partial day to trim. */
  window: { start: string; end: string };
  /** Reported because month totals are not comparable without it. */
  days: number;
  /** The "today" this was built against, so the email is self-describing. */
  generatedFor: string;

  /** The headline. Negative means the month cost more than it brought in. */
  net: { received: number; allInSpent: number; net: number };

  habitual: { spent: number; receiptCount: number };
  /** Travel / School / Rent. Itemized inside `bigSpenders`, not in their own section. */
  excluded: { spent: number };

  savings: { month: number; yearToDate: number };

  bigSpenders: BigSpenderRow[];
  /** Split so the table can foot to two subtotals plus the all-in line. */
  bigSpenderTotals: { habitual: number; excluded: number };

  grid: CategoryMonthGrid;
  projection: Projection;

  /** Unlinked disbursements only — a refund already reduced the spend figure. */
  income: { total: number; count: number; entities: NamedTotal[] };

  /** Habitual spend only. All-in would rank the landlord first every month. */
  topStores: NamedTotal[];

  changes: CategoryChangeRow[];
  quietWins: QuietWinRow[];
  eatingOut: EatingOutSplit | null;
}

// ---------------------------------------------------------------------------
// Statistics
//
// Small and explicit rather than pulled from a library: every one of these is
// four lines, and the digest's credibility rests on being able to check its
// numbers by hand against a literal array.
// ---------------------------------------------------------------------------

function ascending(values: readonly number[]): number[] {
  return [...values].sort((a, b) => a - b);
}

/** Assumes non-empty. */
function median(values: readonly number[]): number {
  const s = ascending(values);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 === 0 ? (s[mid - 1]! + s[mid]!) / 2 : s[mid]!;
}

function mean(values: readonly number[]): number {
  return values.reduce((sum, v) => sum + v, 0) / values.length;
}

/** Drop the highest and lowest month, average the rest. Assumes length ≥ 3. */
function trimmedMean(values: readonly number[]): number {
  return mean(ascending(values).slice(1, -1));
}

/**
 * Linear-interpolated percentile (the PERCENTILE.INC / R type-7 convention).
 *
 * Six points is a crude sample to take a quartile from, and the digest says so
 * by reporting `usableMonths` next to the range rather than presenting it as
 * precise.
 */
function percentile(values: readonly number[], p: number): number {
  const s = ascending(values);
  if (s.length === 1) return s[0]!;
  const idx = p * (s.length - 1);
  const lo = Math.floor(idx);
  const hi = Math.ceil(idx);
  if (lo === hi) return s[lo]!;
  return s[lo]! + (s[hi]! - s[lo]!) * (idx - lo);
}

/**
 * The forecast estimator, and the rule it used.
 *
 * Trimmed mean once there are enough months to trim, median below that. Never
 * a plain mean — one stock-up month must not set a budget — and never a fitted
 * trend, because on six noisy points the slope's standard error is large enough
 * that extrapolating it produces confident nonsense.
 */
function estimate(values: readonly number[]): {
  value: number;
  rule: EstimatorRule;
} {
  if (values.length >= FORECAST_MIN_TRIM_MONTHS) {
    return { value: trimmedMean(values), rule: "trimmed-mean" };
  }
  return { value: median(values), rule: "median" };
}

/**
 * Rising / falling when the recent half diverges from the older half.
 *
 * Exists because the trimmed mean is *deliberately* blind to drift: something
 * has to say when the stable number is about to be wrong. Needs the full
 * baseline — half a series can't have two halves.
 */
function trendOf(series: readonly number[]): TrendDirection | null {
  if (series.length < DIGEST_BASELINE_MONTHS) return null;
  const half = Math.floor(series.length / 2);
  const older = median(series.slice(0, half));
  const recent = median(series.slice(series.length - half));
  if (older <= 0) return null;
  const change = (recent - older) / older;
  if (Math.abs(change) < FORECAST_TREND_THRESHOLD) return null;
  return change > 0 ? "rising" : "falling";
}

function sumBy<T>(rows: readonly T[], value: (row: T) => number): number {
  return rows.reduce((sum, row) => sum + value(row), 0);
}

