/**
 * Each category's typical receipt, over `BIG_SPENDER.medianMonths` ending with
 * the digest's month.
 *
 * **Median, not mean** — the mean is dragged upward by the very outlier the rule
 * exists to detect, so a category with one $600 repair would need a second $600
 * repair to flag. Subscription-generated charges are left out: many identical
 * small charges would drag the median down and make ordinary purchases look
 * exceptional.
 *
 * One map for every month evaluated, taken over the window ending at the digest
 * month rather than recomputed per month. That means a month six back is judged
 * against a median that includes later data — correct here, because this is a
 * baseline for a photograph, not a backtest of a live signal.
 */
function categoryMedians(
  receipts: readonly MergedReceipt[],
  month: string,
): Map<string, number> {
  const from = monthStart(addMonthsToKey(month, -(BIG_SPENDER.medianMonths - 1)));
  const to = monthEnd(month);

  const byCategory = new Map<string, number[]>();
  for (const r of receipts) {
    if (r.date < from || r.date > to) continue;
    if (r.subscription_id != null) continue;
    if (r.actual_price <= 0) continue; // a fully refunded receipt is not a purchase
    const list = byCategory.get(r.category);
    if (list) list.push(r.actual_price);
    else byCategory.set(r.category, [r.actual_price]);
  }

  const out = new Map<string, number>();
  for (const [category, prices] of byCategory) {
    out.set(category, median(prices));
  }
  return out;
}

/**
 * The three rules, unioned (ARCHITECTURE.md).
 *
 * `relativeFloor` guards *both* the relative and the share rule. Without it the
 * share rule turns a $5 receipt into a "big spender" in a $100 month, which is
 * technically 5% and obviously absurd.
 */
function qualifyBigSpender(
  receipt: MergedReceipt,
  medians: Map<string, number>,
  allInSpent: number,
): { reasons: BigSpenderReason[]; categoryMedian: number | null } {
  const reasons: BigSpenderReason[] = [];
  const amount = receipt.actual_price;
  const recurring = receipt.subscription_id != null;

  if (amount >= BIG_SPENDER.absoluteFloor) reasons.push("floor");

  const categoryMedian = medians.get(receipt.category) ?? null;
  const relativeApplies = !recurring && amount >= BIG_SPENDER.relativeFloor;

  if (
    relativeApplies &&
    categoryMedian !== null &&
    categoryMedian > 0 &&
    amount >= categoryMedian * BIG_SPENDER.relativeMultiple
  ) {
    reasons.push("category-relative");
  }

  if (
    relativeApplies &&
    allInSpent > 0 &&
    amount >= allInSpent * BIG_SPENDER.shareOfAllIn
  ) {
    reasons.push("share-of-month");
  }

  return {
    reasons,
    categoryMedian: reasons.includes("category-relative") ? categoryMedian : null,
  };
}

function bigSpendersIn(
  slice: MonthSlice,
  medians: Map<string, number>,
): BigSpenderRow[] {
  const rows: BigSpenderRow[] = [];
  for (const receipt of [...slice.habitual, ...slice.excluded]) {
    const { reasons, categoryMedian } = qualifyBigSpender(
      receipt,
      medians,
      slice.allInSpent,
    );
    if (reasons.length === 0) continue;
    rows.push({
      receiptId: receipt.id,
      date: receipt.date,
      store: receipt.store,
      category: receipt.category,
      amount: receipt.actual_price,
      reasons,
      categoryMedian,
      multipleOfMedian:
        categoryMedian !== null && categoryMedian > 0
          ? receipt.actual_price / categoryMedian
          : null,
      shareOfAllIn:
        slice.allInSpent > 0 ? receipt.actual_price / slice.allInSpent : 0,
      inHabitual: !isExcludedCategory(receipt.category),
      recurring: receipt.subscription_id != null,
    });
  }
  return rows.sort((a, b) => b.amount - a.amount || a.date.localeCompare(b.date));
}

