interface MonthSlice {
  month: string;
  /**
   * The ledger reaches back this far. A month that predates it has no data *for
   * a reason that has nothing to do with spending* — same trap `reports.ts`
   * avoids by dropping baselines rather than counting them as zero.
   */
  covered: boolean;
  habitual: MergedReceipt[];
  excluded: MergedReceipt[];
  habitualSpent: number;
  allInSpent: number;
  /**
   * Habitual spend and receipt count per category, folded in one pass.
   *
   * Precomputed for the reason `reports.ts` precomputes its baseline totals:
   * the grid, the forecast and the change decomposition each want every
   * category in every month, and re-filtering the month's rows once per
   * category turns one pass into `categories × months` of them.
   */
  categorySpent: Map<string, number>;
  categoryCount: Map<string, number>;
}

function sliceMonth(
  byMonth: Map<string, MergedReceipt[]>,
  month: string,
  covered: boolean,
): MonthSlice {
  const rows = byMonth.get(month) ?? [];
  const habitual: MergedReceipt[] = [];
  const excluded: MergedReceipt[] = [];
  const categorySpent = new Map<string, number>();
  const categoryCount = new Map<string, number>();

  for (const r of rows) {
    if (isExcludedCategory(r.category)) {
      excluded.push(r);
      continue;
    }
    habitual.push(r);
    categorySpent.set(
      r.category,
      (categorySpent.get(r.category) ?? 0) + r.actual_price,
    );
    categoryCount.set(r.category, (categoryCount.get(r.category) ?? 0) + 1);
  }

  const habitualSpent = sumBy(habitual, (r) => r.actual_price);
  return {
    month,
    covered,
    habitual,
    excluded,
    habitualSpent,
    allInSpent: habitualSpent + sumBy(excluded, (r) => r.actual_price),
    categorySpent,
    categoryCount,
  };
}

/**
 * Group rows by `nameGroupKey`, displaying the group's most-used spelling.
 *
 * Reuses the Stores/Entities display rule rather than picking, say, the first
 * spelling encountered: the digest and `/stores` must not disagree about what a
 * store is called.
 */
function groupByName<T>(
  rows: readonly T[],
  nameOf: (row: T) => string,
  dateOf: (row: T) => string,
  valueOf: (row: T) => number,
): NamedTotal[] {
  const groups = new Map<
    string,
    { spellings: Map<string, SpellingStat>; total: number; count: number }
  >();

  for (const row of rows) {
    const key = nameGroupKey(nameOf(row));
    let group = groups.get(key);
    if (!group) {
      group = { spellings: new Map(), total: 0, count: 0 };
      groups.set(key, group);
    }
    tallySpelling(group.spellings, nameOf(row), dateOf(row));
    group.total += valueOf(row);
    group.count += 1;
  }

  return [...groups.values()]
    .map((group) => ({
      name: rankSpellings(group.spellings.values())[0]?.spelling ?? "",
      total: group.total,
      count: group.count,
    }))
    .sort((a, b) => b.total - a.total || a.name.localeCompare(b.name));
}

