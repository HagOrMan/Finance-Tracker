const MONTH_NAMES = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

const MONTH_ABBR = [
  "Jan", "Feb", "Mar", "Apr", "May", "Jun",
  "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
];

/**
 * "Jul" — the grid's column header. Pure string work, per `CLAUDE.md`'s date
 * rule, and falls back to the raw key rather than rendering "undefined".
 */
export function formatMonthAbbr(monthKey: string): string {
  return MONTH_ABBR[Number(monthKey.slice(5, 7)) - 1] ?? monthKey;
}

/** "July 2026". */
export function formatMonthLong(monthKey: string): string {
  const name = MONTH_NAMES[Number(monthKey.slice(5, 7)) - 1];
  return name ? `${name} ${monthKey.slice(0, 4)}` : monthKey;
}

/** "July 2026" — the digest's title and subject line. */
export function digestTitle(digest: MonthlyDigest): string {
  return formatMonthLong(digest.month);
}

/** "the 6 months to Jun 2026", or null when there is no usable baseline. */
export function baselineLabel(digest: MonthlyDigest): string | null {
  const months = digest.projection.categories[0]?.usableMonths ?? 0;
  if (months === 0) return null;
  const last = digest.grid.months[digest.grid.months.length - 2];
  if (months === 1) return `the month to ${last ? formatMonthAbbr(last) : ""}`.trim();
  return `the ${months} months to ${last ? formatMonthAbbr(last) : ""}`.trim();
}

/**
 * "3.4× typical Transportation" / "over the $150 floor" / "5% of the month".
 *
 * The reason is the whole point of the table — a bare threshold cannot explain
 * why a brake job belongs in the same list as rent.
 */
export function bigSpenderReasonLabel(row: BigSpenderRow): string {
  if (row.reasons.includes("category-relative") && row.multipleOfMedian !== null) {
    return `${row.multipleOfMedian.toFixed(1)}× typical ${row.category}`;
  }
  if (row.reasons.includes("floor")) {
    return `over the $${BIG_SPENDER.absoluteFloor} floor`;
  }
  return `${Math.round(row.shareOfAllIn * 100)}% of the month`;
}

/** "went 4 more times" / "each visit cost $12 more" — whichever effect dominates. */
export function changeDriverLabel(row: CategoryChangeRow): string {
  const frequency = Math.abs(row.frequencyEffect);
  const ticket = Math.abs(row.ticketEffect);
  const visits = row.receiptCount - row.baselineCount;

  if (frequency >= ticket) {
    const n = Math.abs(visits);
    const rounded = n < 1 ? n.toFixed(1) : Math.round(n).toString();
    return `${visits >= 0 ? "went" : "skipped"} ${rounded} ${
      Math.round(n) === 1 ? "visit" : "visits"
    }`;
  }

  const diff = Math.abs(row.avgTicket - row.baselineAvgTicket);
  return `each visit cost $${diff.toFixed(2)} ${
    row.avgTicket >= row.baselineAvgTicket ? "more" : "less"
  }`;
}
