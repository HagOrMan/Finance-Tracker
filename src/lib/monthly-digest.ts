export function buildMonthlyDigest(
  receipts: MergedReceipt[],
  disbursements: Disbursement[],
  subscriptions: Subscription[],
  month: string,
  today: string,
): MonthlyDigest {
  const start = monthStart(month);
  const end = monthEnd(month);

  // The ledger's own start, for the same reason `reports.ts` computes it: a
  // month before the first receipt is unknown, not empty.
  const ledgerStart = receipts.reduce<string | null>(
    (min, r) => (min === null || r.date < min ? r.date : min),
    null,
  );
  // `monthStart`, not `monthEnd`: the ledger must cover the WHOLE month. A month
  // the ledger only half-covers is a partial month reported as a complete one,
  // which reads as a lean month and biases every baseline built from it — the
  // same trap `reports.ts` avoids by dropping baselines rather than zeroing them.
  const covers = (key: string) =>
    ledgerStart !== null && ledgerStart <= monthStart(key);

  const byMonth = new Map<string, MergedReceipt[]>();
  for (const r of receipts) {
    const key = monthKeyOf(r.date);
    const list = byMonth.get(key);
    if (list) list.push(r);
    else byMonth.set(key, [r]);
  }

  const baselineKeys = precedingMonths(month, DIGEST_BASELINE_MONTHS);
  const gridKeys = [...baselineKeys, month];

  const slices = new Map<string, MonthSlice>(
    gridKeys.map((key) => [key, sliceMonth(byMonth, key, covers(key))]),
  );
  const current = slices.get(month)!;
  const usableBaselines = baselineKeys
    .map((key) => slices.get(key)!)
    .filter((slice) => slice.covered);

  const medians = categoryMedians(receipts, month);

  // ---- big spenders --------------------------------------------------------

  const bigSpenders = bigSpendersIn(current, medians);

  // Per-month one-off sets, so the forecast baseline can be stripped by the
  // same rules that built the table above. Habitual categories only — the
  // excluded ones are outside the projection entirely.
  const oneOffsByMonth = new Map<string, Map<string, number>>();
  for (const slice of usableBaselines) {
    const perCategory = new Map<string, number>();
    for (const row of bigSpendersIn(slice, medians)) {
      if (!row.inHabitual || row.recurring) continue;
      perCategory.set(
        row.category,
        (perCategory.get(row.category) ?? 0) + row.amount,
      );
    }
    oneOffsByMonth.set(slice.month, perCategory);
  }

  const currentOneOffs = new Map<string, number>();
  for (const row of bigSpenders) {
    if (!row.inHabitual || row.recurring) continue;
    currentOneOffs.set(
      row.category,
      (currentOneOffs.get(row.category) ?? 0) + row.amount,
    );
  }

  /** A month's habitual spend in one category, with that month's one-offs removed. */
  const habitualExOneOffs = (slice: MonthSlice, category: string): number => {
    const gross = slice.categorySpent.get(category) ?? 0;
    const oneOff =
      slice.month === month
        ? (currentOneOffs.get(category) ?? 0)
        : (oneOffsByMonth.get(slice.month)?.get(category) ?? 0);
    return gross - oneOff;
  };

  // ---- grid ----------------------------------------------------------------

  const gridCategories = new Set<string>();
  for (const key of gridKeys) {
    const slice = slices.get(key)!;
    if (!slice.covered) continue;
    for (const category of slice.categorySpent.keys()) {
      gridCategories.add(category);
    }
  }

  const allGridRows: CategoryGridRow[] = [...gridCategories]
    .map((category) => {
      const values = gridKeys.map((key) => {
        const slice = slices.get(key)!;
        if (!slice.covered) return null;
        return slice.categorySpent.get(category) ?? 0;
      });
      return {
        category,
        values,
        // Ranked on the whole window, not on this month, so a row can't pop in
        // and out of the grid month to month and break the comparison.
        total: sumBy(values, (v) => v ?? 0),
      };
    })
    .sort((a, b) => b.total - a.total || a.category.localeCompare(b.category));

  const gridRows = allGridRows.slice(0, DIGEST_MAX_GRID_CATEGORIES);
  const gridTail = allGridRows.slice(DIGEST_MAX_GRID_CATEGORIES);

  const grid: CategoryMonthGrid = {
    months: gridKeys,
    rows: gridRows,
    otherRow:
      gridTail.length > 0
        ? {
            category: `${gridTail.length} other categories`,
            values: gridKeys.map((key, i) =>
              slices.get(key)!.covered
                ? sumBy(gridTail, (row) => row.values[i] ?? 0)
                : null,
            ),
            total: sumBy(gridTail, (row) => row.total),
          }
        : null,
    totals: gridKeys.map((key) => {
      const slice = slices.get(key)!;
      return slice.covered ? slice.habitualSpent : null;
    }),
  };

  // ---- projection ----------------------------------------------------------

  // Guarded rather than filtered afterwards: `median([])` and `percentile([])`
  // are NaN, and a NaN that gets filtered out later still had to exist first.
  // On a first-ever digest there are no usable baselines and nothing to project.
  const projectionCategories: ProjectedCategory[] =
    usableBaselines.length === 0
      ? []
      : [...gridCategories]
          .map((category) => {
            const series = usableBaselines.map((slice) =>
              habitualExOneOffs(slice, category),
            );
            const { value, rule } = estimate(series);
            return {
              category,
              perMonth: value,
              low: percentile(series, 0.25),
              high: percentile(series, 0.75),
              rule,
              usableMonths: series.length,
              trend: trendOf(series),
            } satisfies ProjectedCategory;
          })
          .sort(
            (a, b) =>
              b.perMonth - a.perMonth || a.category.localeCompare(b.category),
          );

  // The total is estimated from the total series, NOT by summing the category
  // estimates' ranges. Categories move together — a lean month is lean across
  // the board — so combining their spreads would assume an independence the
  // data does not have. The joint series already carries the real covariance.
  const totalSeries = usableBaselines.map((slice) =>
    sumBy([...gridCategories], (category) => habitualExOneOffs(slice, category)),
  );
  const habitualEstimate =
    totalSeries.length > 0
      ? estimate(totalSeries)
      : { value: 0, rule: "median" as EstimatorRule };
  const habitualPerMonth: ProjectionTotal = {
    total: habitualEstimate.value,
    low: totalSeries.length > 0 ? percentile(totalSeries, 0.25) : 0,
    high: totalSeries.length > 0 ? percentile(totalSeries, 0.75) : 0,
  };

  const nextMonth = addMonthsToKey(month, 1);
  const horizonThrough = addMonthsToKey(nextMonth, FORECAST_HORIZON_MONTHS - 1);

  const subscriptionsNextMonth = projectedSubscriptionSpend(
    subscriptions,
    monthStart(nextMonth),
    monthEnd(nextMonth),
  );
  const subscriptionsHorizon = projectedSubscriptionSpend(
    subscriptions,
    monthStart(nextMonth),
    monthEnd(horizonThrough),
  );

  // √n, not n. Monthly deviations are close to independent, so they partly
  // cancel over a multi-month total: scaling the half-widths linearly would
  // overstate the four-month spread by roughly 2×. The subscription figure is
  // known, so it shifts all three numbers by the same amount and widens nothing.
  const spread = Math.sqrt(FORECAST_HORIZON_MONTHS);
  const lowHalf = habitualPerMonth.total - habitualPerMonth.low;
  const highHalf = habitualPerMonth.high - habitualPerMonth.total;
  const horizonHabitual = habitualPerMonth.total * FORECAST_HORIZON_MONTHS;

  const projection: Projection = {
    nextMonth,
    horizonMonths: FORECAST_HORIZON_MONTHS,
    horizonThrough,
    categories: projectionCategories,
    habitualPerMonth,
    subscriptionsNextMonth,
    subscriptionsHorizon,
    nextMonthTotal: {
      total: habitualPerMonth.total + subscriptionsNextMonth,
      low: habitualPerMonth.low + subscriptionsNextMonth,
      high: habitualPerMonth.high + subscriptionsNextMonth,
    },
    horizonTotal: {
      total: horizonHabitual + subscriptionsHorizon,
      low: horizonHabitual - spread * lowHalf + subscriptionsHorizon,
      high: horizonHabitual + spread * highHalf + subscriptionsHorizon,
    },
    oneOffBuffer:
      usableBaselines.length > 0
        ? mean(
            usableBaselines.map((slice) =>
              sumBy(
                [...(oneOffsByMonth.get(slice.month)?.values() ?? [])],
                (v) => v,
              ),
            ),
          )
        : 0,
  };

  // ---- income --------------------------------------------------------------

  // Unlinked only: a linked disbursement is a refund, and a refund already came
  // off `actual_price`. Counting it here would report the same dollar twice.
  const unlinked = disbursements.filter(
    (d) =>
      d.refunded_from_receipt == null &&
      d.date_received >= start &&
      d.date_received <= end,
  );

  // ---- changes, quiet wins -------------------------------------------------

  const changes: CategoryChangeRow[] = [];
  const quietWins: QuietWinRow[] = [];

  for (const category of gridCategories) {
    const series = usableBaselines.map((slice) =>
      habitualExOneOffs(slice, category),
    );
    if (series.length === 0) continue;

    const baselineSpent = estimate(series).value;
    const oneOffsRemoved = currentOneOffs.get(category) ?? 0;
    const spent = habitualExOneOffs(current, category);

    if (baselineSpent > 0) {
      const drop = (baselineSpent - spent) / baselineSpent;
      if (drop >= DIGEST_QUIET_WIN_THRESHOLD) {
        quietWins.push({
          category,
          spent,
          baseline: baselineSpent,
          delta: spent - baselineSpent,
        });
      }
    }

    const receiptCount = current.categoryCount.get(category) ?? 0;
    const baselineCount = mean(
      usableBaselines.map((slice) => slice.categoryCount.get(category) ?? 0),
    );
    // No visits on one side means there is no average ticket to compare, and a
    // decomposition of "went from nothing to something" is just the total.
    if (receiptCount === 0 || baselineCount === 0) continue;

    const avgTicket = spent / receiptCount;
    // Derived from the estimated spend rather than averaged separately, so
    // baselineCount × baselineAvgTicket === baselineSpent exactly and the two
    // effects sum to the delta with no residual.
    const baselineAvgTicket = baselineSpent / baselineCount;

    changes.push({
      category,
      spent,
      receiptCount,
      oneOffsRemoved,
      baselineSpent,
      baselineCount,
      avgTicket,
      baselineAvgTicket,
      deltaSpent: spent - baselineSpent,
      frequencyEffect:
        (receiptCount - baselineCount) * ((baselineAvgTicket + avgTicket) / 2),
      ticketEffect:
        (avgTicket - baselineAvgTicket) * ((baselineCount + receiptCount) / 2),
    });
  }

  changes.sort((a, b) => Math.abs(b.deltaSpent) - Math.abs(a.deltaSpent));
  quietWins.sort((a, b) => a.delta - b.delta);

  // ---- eating out ----------------------------------------------------------

  const stressedKey = nameGroupKey(EATING_OUT_STRESSED);
  const socialKey = nameGroupKey(EATING_OUT_SOCIAL);
  const eatingOutTotal = (slice: MonthSlice, key: string) =>
    sumBy(
      slice.habitual.filter((r) => nameGroupKey(r.category) === key),
      (r) => r.actual_price,
    );

  const stressed = eatingOutTotal(current, stressedKey);
  const social = eatingOutTotal(current, socialKey);
  const baselineStressed = sumBy(usableBaselines, (s) =>
    eatingOutTotal(s, stressedKey),
  );
  const baselineSocial = sumBy(usableBaselines, (s) =>
    eatingOutTotal(s, socialKey),
  );

  const eatingOut: EatingOutSplit | null =
    stressed + social > 0 || baselineStressed + baselineSocial > 0
      ? {
          stressed,
          social,
          stressedShare:
            stressed + social > 0 ? stressed / (stressed + social) : null,
          baselineStressedShare:
            baselineStressed + baselineSocial > 0
              ? baselineStressed / (baselineStressed + baselineSocial)
              : null,
        }
      : null;

  // ---- savings -------------------------------------------------------------

  // Year to date runs to the END of the digest's month, not to `today`: the
  // digest mails on the 3rd, and a YTD figure that quietly included two days of
  // the following month would not reconcile against the month's own number.
  const yearStart = `${month.slice(0, 4)}-01-01`;
  const savingsYearToDate = sumBy(
    receipts.filter((r) => r.date >= yearStart && r.date <= end),
    computeSavings,
  );

  const receivedTotal = sumBy(unlinked, (d) => d.amount);
  const allInSpent = current.allInSpent;

  return {
    month,
    window: { start, end },
    days: daysInMonth(month),
    generatedFor: today,

    net: {
      received: receivedTotal,
      allInSpent,
      net: receivedTotal - allInSpent,
    },

    habitual: {
      spent: current.habitualSpent,
      receiptCount: current.habitual.length,
    },
    excluded: { spent: sumBy(current.excluded, (r) => r.actual_price) },

    savings: {
      month: sumBy([...current.habitual, ...current.excluded], computeSavings),
      yearToDate: savingsYearToDate,
    },

    bigSpenders,
    bigSpenderTotals: {
      habitual: sumBy(
        bigSpenders.filter((r) => r.inHabitual),
        (r) => r.amount,
      ),
      excluded: sumBy(
        bigSpenders.filter((r) => !r.inHabitual),
        (r) => r.amount,
      ),
    },

    grid,
    projection,

    income: {
      total: receivedTotal,
      count: unlinked.length,
      entities: groupByName(
        unlinked,
        (d) => d.entity,
        (d) => d.date_received,
        (d) => d.amount,
      ),
    },

    topStores: groupByName(
      current.habitual,
      (r) => r.store,
      (r) => r.date,
      (r) => r.actual_price,
    ).slice(0, DIGEST_TOP_STORES),

    changes,
    quietWins,
    eatingOut,
  };
}

