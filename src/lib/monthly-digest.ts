/**
 * The monthly digest — the pure model (ARCHITECTURE.md).
 *
 * **A second lens, not a fourth period.** `src/lib/reports.ts` answers "how was
 * the last N days"; this answers "what did last month cost, and what should I
 * expect next". They cannot be the same model: every field on `SpendingReport`
 * is coherent because all its windows are the same length, and calendar months
 * are 28–31 days.
 *
 * Same discipline as `reports.ts` all the same — everything here is a pure
 * function of `(receipts, disbursements, subscriptions, month, today)`, which is
 * what lets `/reports/monthly` and the email agree about every number by
 * construction. `monthly-digest-runner.ts` does the I/O.
 *
 * The shared primitives are imported rather than re-derived: `isExcludedCategory`
 * so both lenses agree on what Rent is, `nameGroupKey` so store and entity
 * grouping matches `/stores`, `computeSavings` so a discount is worth the same
 * everywhere.
 */

